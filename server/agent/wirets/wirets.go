// Package wirets writes the TypeScript declaration of every type an event is
// serialized as (agent.WireTypes): the records in a session's history and the
// live events broadcast beside them. The web client reads those through the
// file this produces, so the schema has one hand-written copy — the Go types —
// and a check (TestGeneratedFileIsCurrent) instead of a second one to keep in
// step.
//
// The output is derived the way encoding/json derives the JSON: exported
// fields, their tags, embedded structs flattened. Two things reflection cannot
// see come from elsewhere: the `type` discriminator, which is no field but each
// type's Type() written by its MarshalJSON, and the documentation and named
// string constants, which come from the Go source of the type's package.
//
// Anything the derivation cannot describe faithfully — a nested type with a
// MarshalJSON of its own, an interface, a non-string map key, a constant it
// cannot file under its type — fails generation rather than coming out as a
// guess.
package wirets

import (
	"bytes"
	"encoding"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"time"

	"github.com/pockode/server/agent"
)

// OutputPath is the generated file, relative to the server module's root.
const OutputPath = "../web/src/types/wire.generated.ts"

const modulePath = "github.com/pockode/server"

// identifier is a JSON name written as a bare TypeScript property.
var identifier = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

var (
	timeType       = reflect.TypeFor[time.Time]()
	rawMessageType = reflect.TypeFor[json.RawMessage]()
	marshalerType  = reflect.TypeFor[json.Marshaler]()
	textMarshaler  = reflect.TypeFor[encoding.TextMarshaler]()
)

// Generate returns the file's contents. moduleRoot is the server module's
// directory, where the Go source the documentation is read from lives.
func Generate(moduleRoot string) ([]byte, error) {
	g := &generator{
		moduleRoot: moduleRoot,
		packages:   map[string]*packageSource{},
		named:      map[reflect.Type]string{},
		names:      map[string]reflect.Type{},
	}
	return g.run(agent.WireTypes())
}

type generator struct {
	moduleRoot string
	packages   map[string]*packageSource
	// named is every named type declared so far, by the name it is declared
	// under; names is the converse, to refuse two Go types with one name.
	named map[reflect.Type]string
	names map[string]reflect.Type
	// pending are named types referenced but not yet declared, in the order
	// they were first referenced.
	pending []reflect.Type
	out     bytes.Buffer
	// foreign is foreignConsts' answer, read once.
	foreign *packageSource
	// packageNames caches packageName.
	packageNames map[string]string
}

// unionNames are the unions run declares, which no Go type may be declared as.
var unionNames = []string{"HistoryRecord", "LiveEvent", "WireEvent"}

func (g *generator) run(wires []agent.Wire) ([]byte, error) {
	g.out.WriteString(header)
	for _, name := range unionNames {
		g.names[name] = nil
	}

	var records, live []string
	for _, w := range wires {
		t := reflect.TypeOf(w)
		name, err := g.claim(t)
		if err != nil {
			return nil, err
		}
		switch w.(type) {
		case agent.Record:
			records = append(records, name)
		case agent.LiveEvent:
			live = append(live, name)
		default:
			return nil, fmt.Errorf("%s is neither a Record nor a LiveEvent", t)
		}
		if err := g.declareStruct(t, string(w.Type())); err != nil {
			return nil, err
		}
	}

	g.union("Every record a session's history holds, as history.jsonl stores it.",
		"HistoryRecord", records)
	g.union("Every event that is broadcast and never stored: never in history,\n"+
		"never with a seq.", "LiveEvent", live)
	g.union("Every event an agent.Wire can be, discriminated by `type`.",
		"WireEvent", []string{"HistoryRecord", "LiveEvent"})

	for len(g.pending) > 0 {
		t := g.pending[0]
		g.pending = g.pending[1:]
		var err error
		if t.Kind() == reflect.Struct {
			err = g.declareStruct(t, "")
		} else {
			err = g.declareAlias(t)
		}
		if err != nil {
			return nil, err
		}
	}
	return g.out.Bytes(), nil
}

const header = `// Code generated by server/agent/wirets from agent.WireTypes. DO NOT EDIT.
// Regenerate: cd server && UPDATE_WIRE_TYPES=1 go test ./agent/wirets
//
// The shape of every history record and live event as the server's Go types
// declare it: snake_case, and a field marked optional is one the server omits
// when empty. What a type says is what this server writes, not what every
// stored line holds: a record from an older build may lack a field, and a
// value a CLI hands through unchecked (a plan step's status, a permission
// suggestion) may be one no constant names. Convert to the client's own types,
// checking those, where the transcript items are read (lib/transcript.ts) —
// never by editing this file.
`

func (g *generator) union(docText, name string, members []string) {
	g.out.WriteString("\n")
	g.writeDoc("", docText)
	g.writeUnion(name, members)
}

// writeUnion declares a union the way Biome formats one: on one line when it
// fits in 80 columns, a member a line otherwise.
func (g *generator) writeUnion(name string, members []string) {
	line := fmt.Sprintf("export type %s = %s;", name, strings.Join(members, " | "))
	if len(line) <= 80 {
		g.out.WriteString(line + "\n")
		return
	}
	fmt.Fprintf(&g.out, "export type %s =\n", name)
	for i, m := range members {
		fmt.Fprintf(&g.out, "\t| %s", m)
		if i == len(members)-1 {
			g.out.WriteString(";")
		}
		g.out.WriteString("\n")
	}
}

// claim reserves t's TypeScript name, which is its Go name.
func (g *generator) claim(t reflect.Type) (string, error) {
	if name, ok := g.named[t]; ok {
		return name, nil
	}
	name := t.Name()
	if other, taken := g.names[name]; taken {
		if other == nil {
			return "", fmt.Errorf("%s would be declared as %s, which is one of the generated unions", t, name)
		}
		return "", fmt.Errorf("two types would be declared as %s: %s and %s", name, other, t)
	}
	g.named[t] = name
	g.names[name] = t
	return name, nil
}

// declareStruct writes t as an interface. discriminator is the `type` value a
// wire type's MarshalJSON writes in front of its fields; empty for a nested
// struct, which has no such field.
func (g *generator) declareStruct(t reflect.Type, discriminator string) error {
	src, err := g.source(t)
	if err != nil {
		return err
	}
	g.out.WriteString("\n")
	g.writeDoc("", src.typeDocs[t.Name()])
	fmt.Fprintf(&g.out, "export interface %s {\n", t.Name())
	if discriminator != "" {
		fmt.Fprintf(&g.out, "\ttype: %s;\n", strconv.Quote(discriminator))
	}
	fields, err := g.fields(t)
	if err != nil {
		return err
	}
	for _, f := range fields {
		if discriminator != "" && f.name == "type" {
			return fmt.Errorf("%s has a field written as \"type\", which is the discriminator's", t)
		}
	}
	for _, f := range fields {
		g.writeDoc("\t", f.doc)
		optional := ""
		if f.optional {
			optional = "?"
		}
		fmt.Fprintf(&g.out, "\t%s%s: %s;\n", f.name, optional, f.ts)
	}
	g.out.WriteString("}\n")
	return nil
}

type field struct {
	name     string
	optional bool
	ts       string
	doc      string
}

// fields lists t's fields as encoding/json writes them, embedded structs
// flattened in place. Two fields with one JSON name fail: encoding/json would
// resolve them by depth and tags, and a type relying on that is clearer
// written out.
func (g *generator) fields(t reflect.Type) ([]field, error) {
	out, err := g.collectFields(t, false)
	if err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	for _, f := range out {
		if seen[f.name] {
			return nil, fmt.Errorf("%s: two fields are written as %q", t, f.name)
		}
		seen[f.name] = true
	}
	return out, nil
}

// collectFields is fields before the duplicate check. viaPointer says t is
// embedded through a pointer, which when nil writes none of its fields.
func (g *generator) collectFields(t reflect.Type, viaPointer bool) ([]field, error) {
	src, err := g.source(t)
	if err != nil {
		return nil, err
	}
	var out []field
	for i := range t.NumField() {
		f := t.Field(i)
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		// Which fields encoding/json writes at all: an exported field, or an
		// embedded struct, exported or not.
		et := f.Type
		pointer := et.Kind() == reflect.Pointer
		if pointer {
			et = et.Elem()
		}
		embeddedStruct := f.Anonymous && et.Kind() == reflect.Struct
		if !f.IsExported() && !embeddedStruct {
			continue
		}
		if opts != "omitempty" && opts != "" {
			return nil, fmt.Errorf("%s.%s: json option %q is not supported", t, f.Name, opts)
		}
		// An embedded struct with no name in its tag is flattened, whatever
		// else the tag says.
		if embeddedStruct && name == "" {
			if err := g.refuseMarshaler(et); err != nil {
				return nil, err
			}
			inner, err := g.collectFields(et, viaPointer || pointer)
			if err != nil {
				return nil, err
			}
			out = append(out, inner...)
			continue
		}
		if name == "" {
			name = f.Name
		}
		// A name encoding/json would not take from the tag, or that would need
		// quoting as a property, is refused rather than written as a guess.
		if !identifier.MatchString(name) {
			return nil, fmt.Errorf("%s.%s: JSON name %q is not a plain identifier", t, f.Name, name)
		}
		// encoding/json never omits a struct value, omitempty or not.
		omitempty := opts == "omitempty" && f.Type.Kind() != reflect.Struct
		ts, err := g.typeOf(f.Type, !omitempty)
		if err != nil {
			return nil, fmt.Errorf("%s.%s: %w", t, f.Name, err)
		}
		out = append(out, field{
			name:     name,
			optional: omitempty || viaPointer,
			ts:       ts,
			doc:      src.fieldDocs[t.Name()+"."+f.Name],
		})
	}
	return out, nil
}

// typeOf is the TypeScript for a value of t. nullable says the field is
// written even when empty, where a nil pointer, slice or map is `null`.
func (g *generator) typeOf(t reflect.Type, nullable bool) (string, error) {
	orNull := func(s string) string {
		if nullable {
			return s + " | null"
		}
		return s
	}
	switch t {
	case timeType:
		// RFC 3339, as time.Time marshals.
		return "string", nil
	case rawMessageType:
		// Any JSON at all, `null` included.
		return "unknown", nil
	}
	if t.Kind() == reflect.Pointer {
		// What a set pointer points at is always written, so a nil inside it
		// (`*[]T`, `**T`) is `null`.
		inner, err := g.typeOf(t.Elem(), true)
		if err != nil {
			return "", err
		}
		return orNull(inner), nil
	}
	if err := g.refuseMarshaler(t); err != nil {
		return "", err
	}
	switch t.Kind() {
	case reflect.Slice:
		if err := g.refuseMarshaler(t.Elem()); err != nil {
			return "", err
		}
		if t.Elem().Kind() == reflect.Uint8 {
			// encoding/json writes a []byte as base64.
			return orNull("string"), nil
		}
		// An element is always written, so a nil one is `null`.
		inner, err := g.typeOf(t.Elem(), true)
		if err != nil {
			return "", err
		}
		if strings.Contains(inner, " ") {
			inner = "(" + inner + ")"
		}
		return orNull(inner + "[]"), nil
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", fmt.Errorf("map key %s is not a string", t.Key())
		}
		// The key stays `string` even for a named type with constants: a
		// Record keyed by a union would require every key.
		value, err := g.typeOf(t.Elem(), true)
		if err != nil {
			return "", err
		}
		return orNull("Record<string, " + value + ">"), nil
	case reflect.Struct:
		return g.reference(t)
	case reflect.String, reflect.Bool,
		reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		if t.Name() != "" && t.PkgPath() != "" {
			return g.reference(t)
		}
		return basic(t.Kind()), nil
	}
	return "", fmt.Errorf("no TypeScript for %s (%s)", t, t.Kind())
}

func basic(k reflect.Kind) string {
	switch k {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	}
	return "number"
}

// reference names a named type, queueing its declaration.
func (g *generator) reference(t reflect.Type) (string, error) {
	if t.Name() == "" {
		return "", fmt.Errorf("anonymous struct %s: give it a name", t)
	}
	if strings.Contains(t.Name(), "[") {
		return "", fmt.Errorf("generic type %s: TypeScript would need its parameters", t)
	}
	if _, ok := g.named[t]; !ok {
		g.pending = append(g.pending, t)
	}
	return g.claim(t)
}

// refuseMarshaler fails for a type whose JSON is its own code's rather than
// its fields': reflection cannot see what that code writes.
func (g *generator) refuseMarshaler(t reflect.Type) error {
	if t.Implements(marshalerType) || reflect.PointerTo(t).Implements(marshalerType) ||
		t.Implements(textMarshaler) || reflect.PointerTo(t).Implements(textMarshaler) {
		return fmt.Errorf("%s marshals itself; describe it by hand in the generator", t)
	}
	return nil
}

// declareAlias writes a named non-struct type: a union of its constants when
// the module declares any — its own package's first, then other packages' in
// path order — and its underlying type otherwise.
func (g *generator) declareAlias(t reflect.Type) error {
	src, err := g.source(t)
	if err != nil {
		return err
	}
	var values []string
	if t.Kind() == reflect.String {
		if values, err = g.constValues(src, t.PkgPath(), t.Name()); err != nil {
			return err
		}
	}
	members, err := unionMembers(t, values)
	if err != nil {
		return err
	}
	g.out.WriteString("\n")
	g.writeDoc("", src.typeDocs[t.Name()])
	g.writeUnion(t.Name(), members)
	return nil
}

// constValues is every constant the module declares of the string type name
// in package pkgPath, whose own source is src: the package's own first, then
// other packages' in path order. It fails on a constant it found but could not
// file under the type, which would otherwise drop out of the union unnoticed.
func (g *generator) constValues(src *packageSource, pkgPath, name string) ([]string, error) {
	shown := pkgPath[strings.LastIndex(pkgPath, "/")+1:] + "." + name
	if src.unreadable[name] {
		return nil, fmt.Errorf("%s has a constant whose value is not a string literal, or an alias of it (a constant of which would be filed under the alias); write the constant as `Name %s = \"literal\"`", shown, shown)
	}
	foreign, err := g.foreignConsts()
	if err != nil {
		return nil, err
	}
	key := pkgPath + "." + name
	// Another package writing a constant through an alias the type's own
	// package declares (a.Alias for a.Kind) files it under the alias.
	throughAlias := false
	for alias, target := range src.aliases {
		k := pkgPath + "." + alias
		if target == name && (len(foreign.consts[k]) > 0 || foreign.unreadable[k]) {
			throughAlias = true
		}
	}
	if foreign.unreadable[key] || throughAlias {
		return nil, fmt.Errorf("%s has a constant in another package that is not written `Name %s = \"literal\"`, or is written through an alias; write it as one", shown, shown)
	}
	if foreign.dotImported[pkgPath] {
		return nil, fmt.Errorf("%s: a package of the module dot-imports %s, whose constants of it cannot be told from its own; import it by name", shown, pkgPath)
	}
	return slices.Concat(src.consts[name], foreign.consts[key]), nil
}

// unionMembers is a named type's TypeScript members: its constants' values,
// quoted, or its underlying type when it has none.
func unionMembers(t reflect.Type, values []string) ([]string, error) {
	if len(values) == 0 {
		return []string{basic(t.Kind())}, nil
	}
	members := make([]string, len(values))
	seen := map[string]bool{}
	for i, v := range values {
		// Two constants of one value are a copy left behind, or one per
		// platform; either way which of them a sender uses is not the
		// union's to say, and one shared constant says it once.
		if seen[v] {
			return nil, fmt.Errorf("%s has the value %q twice: declare it once (per-platform files included)", t, v)
		}
		seen[v] = true
		members[i] = strconv.Quote(v)
	}
	return members, nil
}

// writeDoc writes a Go doc comment as a TSDoc block, as written: it names Go
// identifiers, which is where a reader follows it to.
func (g *generator) writeDoc(indent, text string) {
	text = strings.TrimSpace(text)
	if text == "" {
		return
	}
	// "*/" would end the block early.
	text = strings.ReplaceAll(text, "*/", "*\\/")
	g.out.WriteString(indent + "/**\n")
	for line := range strings.SplitSeq(text, "\n") {
		if line == "" {
			g.out.WriteString(indent + " *\n")
		} else {
			g.out.WriteString(indent + " * " + line + "\n")
		}
	}
	g.out.WriteString(indent + " */\n")
}

// foreignConsts reads, keyed "pkgpath.Name", the constants every package of
// the module declares of a type from another package — which parsePackage,
// reading only the type's own, would leave out of the type's union. A type is
// given its values where they mean something: agent.MessageSubtype's by the
// packages that send each kind of message. They are read under the same rules
// as a package's own, so a form that cannot be read refuses the type rather
// than leaving a member out.
func (g *generator) foreignConsts() (*packageSource, error) {
	if g.foreign != nil {
		return g.foreign, nil
	}
	foreign := &packageSource{consts: map[string][]string{}, unreadable: map[string]bool{}, dotImported: map[string]bool{}}
	fset := token.NewFileSet()
	err := filepath.WalkDir(g.moduleRoot, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		name := d.Name()
		if d.IsDir() {
			if path != g.moduleRoot && (strings.HasPrefix(name, ".") || name == "testdata" || name == "static") {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			return nil
		}
		file, err := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
		if err != nil {
			return err
		}
		imports := map[string]string{}
		for _, imp := range file.Imports {
			p, _ := strconv.Unquote(imp.Path.Value)
			local, err := g.packageName(p)
			if err != nil {
				return fmt.Errorf("%s: %w", path, err)
			}
			if imp.Name != nil {
				local = imp.Name.Name
			}
			if local == "." {
				// Its constants name the package's types without saying whose
				// they are.
				foreign.dotImported[p] = true
				continue
			}
			imports[local] = p
		}
		imported := func(e ast.Expr) string {
			if sel, ok := e.(*ast.SelectorExpr); ok {
				if x, ok := sel.X.(*ast.Ident); ok && imports[x.Name] != "" {
					return imports[x.Name] + "." + sel.Sel.Name
				}
			}
			return ""
		}
		consts, _ := constDecls(file)
		for _, c := range consts {
			if err := foreign.addConsts(c.gen, c.qualify(imported)); err != nil {
				return fmt.Errorf("%s: %w", path, err)
			}
		}
		// A constant declared through `type A = pkg.T` names A, and which of
		// the package's files declares A is not this file's to know: the alias
		// alone refuses T.
		ast.Inspect(file, func(n ast.Node) bool {
			if ts, ok := n.(*ast.TypeSpec); ok && ts.Assign.IsValid() {
				if key := imported(ast.Unparen(ts.Type)); key != "" {
					foreign.unreadable[key] = true
				}
			}
			return true
		})
		return nil
	})
	if err != nil {
		return nil, err
	}
	g.foreign = foreign
	return foreign, nil
}

// packageName is the name an import of path brings into a file when it gives
// none: read from the package clauses for a package of this module, since a
// package need not be named after its directory, and the last path element
// for any other, whose types the generator refuses anyway. A file under a
// build constraint is read only when every file is: `//go:build ignore` is
// how a generator script (`package main`) sits in another package's directory.
func (g *generator) packageName(path string) (string, error) {
	rel, ok := strings.CutPrefix(path, modulePath+"/")
	if !ok {
		return path[strings.LastIndex(path, "/")+1:], nil
	}
	if name, ok := g.packageNames[path]; ok {
		return name, nil
	}
	if g.packageNames == nil {
		g.packageNames = map[string]string{}
	}
	dir := filepath.Join(g.moduleRoot, filepath.FromSlash(rel))
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", err
	}
	plain, constrained := map[string]bool{}, map[string]bool{}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") {
			continue
		}
		file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, e.Name()), nil,
			parser.PackageClauseOnly|parser.ParseComments)
		if err != nil {
			return "", err
		}
		if hasBuildConstraint(file) {
			constrained[file.Name.Name] = true
		} else {
			plain[file.Name.Name] = true
		}
	}
	names := plain
	if len(names) == 0 {
		names = constrained
	}
	if len(names) != 1 {
		return "", fmt.Errorf("package %s: its files name %d packages, so which name an import of it brings in is a guess", path, len(names))
	}
	var name string
	for n := range names {
		name = n
	}
	g.packageNames[path] = name
	return name, nil
}

// hasBuildConstraint reports a `//go:build` line above the package clause.
func hasBuildConstraint(file *ast.File) bool {
	for _, group := range file.Comments {
		if group.Pos() > file.Package {
			break
		}
		for _, c := range group.List {
			if strings.HasPrefix(c.Text, "//go:build ") {
				return true
			}
		}
	}
	return false
}

// scopedConst is a constant declaration, with the type names declared in the
// function it is in, if any: inside a function those shadow the package's
// own, so a constant of one is not a constant of the package-level type.
type scopedConst struct {
	gen    *ast.GenDecl
	shadow map[string]bool
}

// qualify is q with the shadowed names refused.
func (c scopedConst) qualify(q func(ast.Expr) string) func(ast.Expr) string {
	if len(c.shadow) == 0 {
		return q
	}
	return func(e ast.Expr) string {
		if id, ok := e.(*ast.Ident); ok && c.shadow[id.Name] {
			return ""
		}
		return q(e)
	}
}

// constDecls is every constant declaration in a file, a function's own
// included: a constant of a wire type declared inside a function is still one
// the type's union has to have. localAliases are the targets of the aliases
// functions declare (`type K = Kind`), whose constants are filed under K and
// so would leave Kind's union without a word; a target a function shadows is
// left out.
func constDecls(file *ast.File) (consts []scopedConst, localAliases []ast.Expr) {
	body := func(block *ast.BlockStmt) {
		shadow := map[string]bool{}
		var aliases []*ast.TypeSpec
		ast.Inspect(block, func(n ast.Node) bool {
			if ts, ok := n.(*ast.TypeSpec); ok {
				shadow[ts.Name.Name] = true
				if ts.Assign.IsValid() {
					aliases = append(aliases, ts)
				}
			}
			return true
		})
		ast.Inspect(block, func(n ast.Node) bool {
			if gen, ok := n.(*ast.GenDecl); ok && gen.Tok == token.CONST {
				consts = append(consts, scopedConst{gen: gen, shadow: shadow})
			}
			return true
		})
		for _, ts := range aliases {
			target := ast.Unparen(ts.Type)
			if id, ok := target.(*ast.Ident); ok && shadow[id.Name] {
				continue
			}
			localAliases = append(localAliases, target)
		}
	}
	for _, decl := range file.Decls {
		if gen, ok := decl.(*ast.GenDecl); ok && gen.Tok == token.CONST {
			consts = append(consts, scopedConst{gen: gen})
			continue
		}
		// A function's body, or a function literal's at package level
		// (`var f = func() { … }`).
		ast.Inspect(decl, func(n ast.Node) bool {
			switch n := n.(type) {
			case *ast.FuncDecl:
				if n.Body != nil {
					body(n.Body)
				}
				return false
			case *ast.FuncLit:
				body(n.Body)
				return false
			}
			return true
		})
	}
	return consts, localAliases
}

// packageSource is what the Go source of one package says that reflection
// cannot: documentation, and the constants each named type has.
type packageSource struct {
	typeDocs  map[string]string
	fieldDocs map[string]string // "Type.Field"
	consts    map[string][]string
	// unreadable are the types with a constant whose value this does not read
	// (iota, a conversion, another constant), for declareAlias to refuse
	// rather than leave a member out of the union.
	unreadable map[string]bool
	declared   map[string]bool
	// aliases maps `type A = B` to B, whose constants A's are.
	aliases map[string]string
	// dotImported are the packages some file of the module imports with `.`
	// (foreignConsts only).
	dotImported map[string]bool
}

func (g *generator) source(t reflect.Type) (*packageSource, error) {
	pkg := t.PkgPath()
	if src, ok := g.packages[pkg]; ok {
		return src, nil
	}
	rel, ok := strings.CutPrefix(pkg, modulePath+"/")
	if !ok {
		return nil, fmt.Errorf("%s is from %s, outside this module: describe it by hand in the generator", t, pkg)
	}
	src, err := parsePackage(filepath.Join(g.moduleRoot, filepath.FromSlash(rel)))
	if err != nil {
		return nil, err
	}
	g.packages[pkg] = src
	return src, nil
}

func parsePackage(dir string) (*packageSource, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	src := &packageSource{
		typeDocs:   map[string]string{},
		fieldDocs:  map[string]string{},
		consts:     map[string][]string{},
		unreadable: map[string]bool{},
		declared:   map[string]bool{},
		aliases:    map[string]string{},
	}
	fset := token.NewFileSet()
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			if gen.Tok == token.TYPE {
				if err := src.addTypes(gen); err != nil {
					return nil, fmt.Errorf("%s: %w", name, err)
				}
			}
		}
		consts, localAliases := constDecls(file)
		for _, c := range consts {
			if err := src.addConsts(c.gen, c.qualify(ownType)); err != nil {
				return nil, fmt.Errorf("%s: %w", name, err)
			}
		}
		for _, target := range localAliases {
			if key := ownType(target); key != "" {
				src.unreadable[key] = true
			}
		}
	}
	// A constant declared through an alias is its target's, and one this did
	// not file under the target is one the target's union would miss.
	for alias, target := range src.aliases {
		if len(src.consts[alias]) > 0 || src.unreadable[alias] {
			src.unreadable[target] = true
		}
	}
	return src, nil
}

// addTypes records each type's documentation. A type declared twice — once per
// platform, under build tags — fails: which declaration is the wire's would be
// a guess.
func (src *packageSource) addTypes(gen *ast.GenDecl) error {
	for _, spec := range gen.Specs {
		ts := spec.(*ast.TypeSpec)
		if src.declared[ts.Name.Name] {
			return fmt.Errorf("type %s is declared twice", ts.Name.Name)
		}
		src.declared[ts.Name.Name] = true
		if ts.Assign.IsValid() {
			if target, ok := ts.Type.(*ast.Ident); ok {
				src.aliases[ts.Name.Name] = target.Name
			}
		}
		docGroup := ts.Doc
		if docGroup == nil && len(gen.Specs) == 1 {
			docGroup = gen.Doc
		}
		src.typeDocs[ts.Name.Name] = docText(docGroup)
		st, ok := ts.Type.(*ast.StructType)
		if !ok {
			continue
		}
		for _, f := range st.Fields.List {
			for _, n := range f.Names {
				src.fieldDocs[ts.Name.Name+"."+n.Name] = docText(f.Doc)
			}
		}
	}
	return nil
}

// addConsts records each string constant declared with an explicit named
// type, in declaration order, under the key qualify gives that type. A spec
// that repeats the one before it (no type, no value: iota's form) belongs to
// that one's type. qualify returns "" for a type expression this call does
// not file constants for.
func (src *packageSource) addConsts(gen *ast.GenDecl, qualify func(ast.Expr) string) error {
	var typeName string
	for _, spec := range gen.Specs {
		vs := spec.(*ast.ValueSpec)
		if vs.Type == nil {
			if len(vs.Values) > 0 {
				// An untyped constant, or `X = T("v")`: either way not
				// declared with a type this reads.
				typeName = ""
				for _, v := range vs.Values {
					ast.Inspect(v, func(n ast.Node) bool {
						if call, ok := n.(*ast.CallExpr); ok {
							if key := qualify(ast.Unparen(call.Fun)); key != "" {
								src.unreadable[key] = true
							}
						}
						return true
					})
				}
				continue
			}
			if typeName != "" {
				src.unreadable[typeName] = true
			}
			continue
		}
		typeName = qualify(ast.Unparen(vs.Type))
		if typeName == "" {
			continue
		}
		for _, v := range vs.Values {
			lit, ok := v.(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				src.unreadable[typeName] = true
				continue
			}
			s, err := strconv.Unquote(lit.Value)
			if err != nil {
				return err
			}
			src.consts[typeName] = append(src.consts[typeName], s)
		}
	}
	return nil
}

// ownType is addConsts' qualify for a package's own source: a type named
// without a package.
func ownType(e ast.Expr) string {
	if id, ok := e.(*ast.Ident); ok {
		return id.Name
	}
	return ""
}

// docText is a doc comment's text, its lines as written.
func docText(group *ast.CommentGroup) string {
	if group == nil {
		return ""
	}
	return strings.TrimRight(group.Text(), "\n")
}
